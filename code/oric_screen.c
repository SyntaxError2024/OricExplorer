OricScreenMode oric_detect_screen_mode(const OricFileEntry *entry, size_t payloadSize) {
    if (!entry || payloadSize < 40) return ORIC_SCR_NONE;
    if (entry->isBasic) return ORIC_SCR_NONE;

    if (entry->hasStartEnd) {
        if (entry->startAddr == 0xA000u && payloadSize >= 4000u) {
            return ORIC_SCR_HIRES;
        }
        if (entry->startAddr == 0xBB80u && payloadSize >= 800u && payloadSize <= 1400u) {
            return ORIC_SCR_TEXT;
        }
    }

    if (entry->isScreen) {
        if (payloadSize >= 7000u && payloadSize <= 8400u) {
            return ORIC_SCR_HIRES;
        }
        if (payloadSize >= 1000u && payloadSize <= 1200u) {
            return ORIC_SCR_TEXT;
        }
    }

    return ORIC_SCR_NONE;
}

bool oric_render_screen(const uint8_t *payload,
                        size_t payloadSize,
                        OricScreenMode mode,
                        uint32_t **outBgraPixels,
                        int *outWidth,
                        int *outHeight) {
    if (!payload || payloadSize == 0 || !outBgraPixels || !outWidth || !outHeight ||
        mode == ORIC_SCR_NONE) {
        return false;
    }

    int w = 240;
    int h = (mode == ORIC_SCR_HIRES) ? 200 : 224;
    uint32_t *pix = (uint32_t *)malloc((size_t)w * (size_t)h * sizeof(uint32_t));
    if (!pix) return false;

    if (mode == ORIC_SCR_HIRES) {
        for (int y = 0; y < 200; y++) {
            uint8_t ink = 7;
            uint8_t paper = 0;
            for (int col = 0; col < 40; col++) {
                size_t idx = (size_t)y * 40u + (size_t)col;
                uint8_t b = (idx < payloadSize) ? payload[idx] : 0x40u;
                bool inv = (b & 0x80u) != 0;
                uint8_t val = b & 0x7Fu;

                uint32_t cPaper = ORIC_PALETTE[paper];
                uint32_t cInk = ORIC_PALETTE[ink];
                if (inv) {
                    cPaper = (cPaper ^ 0x00FFFFFFu) | 0xFF000000u;
                    cInk = (cInk ^ 0x00FFFFFFu) | 0xFF000000u;
                }

                if ((val & 0x60u) == 0x00u) {
                    /* Octet attribut série ULA : affiche 6 pixels de paper avec les anciennes couleurs ou nouvelles */
                    if (val <= 0x07u) {
                        ink = val & 0x07u;
                    } else if (val >= 0x10u && val <= 0x17u) {
                        paper = val & 0x07u;
                    }
                    cPaper = ORIC_PALETTE[paper];
                    if (inv) cPaper = (cPaper ^ 0x00FFFFFFu) | 0xFF000000u;
                    for (int px = 0; px < 6; px++) {
                        pix[y * w + col * 6 + px] = cPaper;
                    }
                } else {
                    /* Octet bitmap 6 bits (bit5..bit0) */
                    for (int px = 0; px < 6; px++) {
                        bool on = ((val >> (5 - px)) & 1u) != 0;
                        pix[y * w + col * 6 + px] = on ? cInk : cPaper;
                    }
                }
            }
        }
    } else {
        /* TEXT 40x28 */
        for (int row = 0; row < 28; row++) {
            uint8_t ink = 7;
            uint8_t paper = 0;
            bool dblHeight = false;

            for (int col = 0; col < 40; col++) {
                size_t idx = (size_t)row * 40u + (size_t)col;
                uint8_t b = (idx < payloadSize) ? payload[idx] : 0x20u;
                bool inv = (b & 0x80u) != 0;
                uint8_t val = b & 0x7Fu;

                if (val < 0x20u) {
                    if (val <= 0x07u) ink = val & 0x07u;
                    else if (val >= 0x10u && val <= 0x17u) paper = val & 0x07u;
                    else if (val >= 0x08u && val <= 0x0Fu) dblHeight = ((val & 0x02u) != 0);

                    uint32_t cPaper = ORIC_PALETTE[paper];
                    if (inv) cPaper = (cPaper ^ 0x00FFFFFFu) | 0xFF000000u;
                    for (int ry = 0; ry < 8; ry++) {
                        for (int px = 0; px < 6; px++) {
                            pix[(row * 8 + ry) * w + col * 6 + px] = cPaper;
                        }
                    }
                } else {
                    uint32_t cPaper = ORIC_PALETTE[paper];
                    uint32_t cInk = ORIC_PALETTE[ink];
                    if (inv) {
                        cPaper = (cPaper ^ 0x00FFFFFFu) | 0xFF000000u;
                        cInk = (cInk ^ 0x00FFFFFFu) | 0xFF000000u;
                    }
                    const uint8_t *glyph = FONT_6X8[val - 0x20u];
                    for (int ry = 0; ry < 8; ry++) {
                        int srcRow = dblHeight ? (ry / 2 + ((row & 1) ? 4 : 0)) : ry;
                        uint8_t bits = glyph[srcRow & 7];
                        for (int px = 0; px < 6; px++) {
                            bool on = ((bits >> (5 - px)) & 1u) != 0;
                            pix[(row * 8 + ry) * w + col * 6 + px] = on ? cInk : cPaper;
                        }
                    }
                }
            }
        }
    }

    *outBgraPixels = pix;
    *outWidth = w;
    *outHeight = h;
    return true;
}
